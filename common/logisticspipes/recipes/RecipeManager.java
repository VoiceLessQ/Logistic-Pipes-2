package logisticspipes.recipes;

import net.minecraft.core.registries.BuiltInRegistries;

import java.util.ArrayList;
import java.util.Arrays;
import java.util.LinkedHashMap;
import java.util.List;
import java.util.Map;
import javax.annotation.Nonnull;

import net.minecraft.world.level.block.Block;
import net.minecraft.world.item.Item;
import net.minecraft.world.item.ItemStack;
import net.minecraft.resources.Identifier;

import com.google.gson.Gson;
import com.google.gson.GsonBuilder;
import com.google.gson.JsonArray;
import com.google.gson.JsonObject;
import com.google.gson.JsonPrimitive;
import com.google.gson.JsonElement;
import lombok.AllArgsConstructor;
import lombok.Getter;

import logisticspipes.LPConstants;

public class RecipeManager {

	public static final List<IRecipeProvider> recipeProvider = new ArrayList<>();
	public static final LocalCraftingManager craftingManager = new LocalCraftingManager();

	private static boolean loaded;

	/** Builds the virtual recipes on first data-pack read: ItemStacks need bound item components, which mod init predates. */
	public static synchronized void loadRecipes() {
		if (loaded) return;
		loaded = true;
		recipeProvider.forEach(IRecipeProvider::loadRecipes);
	}

	@AllArgsConstructor
	@Getter
	public static class RecipeIndex {

		private char index;
		private Object value;
	}

	@AllArgsConstructor
	@Getter
	public static class RecipeLayout {

		private String line1;
		private String line2;
		private String line3;
	}

	@AllArgsConstructor
	@Getter
	public static class RecipeLayoutSmall {

		private String line1;
		private String line2;
	}

	@AllArgsConstructor
	@Getter
	public static class RecipeLayoutSmaller {

		private String line1;
	}

	public static class LocalCraftingManager {

		private static final Gson GSON = new GsonBuilder().setPrettyPrinting().create();

		/** Recipes generated by providers at startup, served via LPRecipePack virtual data pack. */
		public final Map<Identifier, String> virtualRecipes = new LinkedHashMap<>();

		public LocalCraftingManager() {
		}

		public void addRecipe(@Nonnull Item output, int count, Object... objects) {
			List<Object> result = new ArrayList<>();
			final boolean[] addRecipe = { true };
			Object layout = null;
			List<RecipeIndex> indices = new ArrayList<>();

			Arrays.stream(objects).forEach(o -> {
				if (!addRecipe[0]) return;
				if (o instanceof RecipeLayout || o instanceof RecipeLayoutSmall || o instanceof RecipeLayoutSmaller) {
					result.add(o);
				} else if (o instanceof RecipeIndex) {
					RecipeIndex ri = (RecipeIndex) o;
					result.add(ri.getIndex());
					result.add(ri.getValue());
					if (ri.getValue() == null) {
						addRecipe[0] = false;
					} else {
						indices.add(ri);
					}
				} else {
					result.add(o);
				}
			});
			if (!addRecipe[0]) return;

			// Find layout object
			for (Object o : objects) {
				if (o instanceof RecipeLayout || o instanceof RecipeLayoutSmall || o instanceof RecipeLayoutSmaller) {
					layout = o;
					break;
				}
			}
			if (layout == null) return;

			String json = dumpRecipe(output, count, layout, indices.toArray(new RecipeIndex[0]));
			if (json != null) {
				Identifier loc = getFreeRecipeResourceLocation(output);
				virtualRecipes.put(loc, json);
			}
		}

		/** Generates a shaped crafting recipe JSON string. Returns null if any ingredient is unhandled. */
		private String dumpRecipe(@Nonnull Item result, int count, Object layout, RecipeIndex... indices) {
			JsonObject obj = new JsonObject();
			JsonArray pattern = new JsonArray();
			JsonObject keys = new JsonObject();
			obj.addProperty("type", "minecraft:crafting_shaped");

			if (layout instanceof RecipeLayout) {
				pattern.add(((RecipeLayout) layout).getLine1());
				pattern.add(((RecipeLayout) layout).getLine2());
				pattern.add(((RecipeLayout) layout).getLine3());
			} else if (layout instanceof RecipeLayoutSmall) {
				pattern.add(((RecipeLayoutSmall) layout).getLine1());
				pattern.add(((RecipeLayoutSmall) layout).getLine2());
			} else if (layout instanceof RecipeLayoutSmaller) {
				pattern.add(((RecipeLayoutSmaller) layout).getLine1());
			}

			for (RecipeIndex index : indices) {
				// Only include keys that actually appear in the pattern
				String patternStr = pattern.toString();
				if (!patternStr.contains(String.valueOf(index.getIndex()))) continue;

				// 26.x ingredients: "<item id>", "#<tag>" or a Fabric custom ingredient object
				JsonElement key;
				if (index.getValue() instanceof String) {
					// Ore dict name to a conventional tag, or "item:<id>" when no common tag exists.
					String mapped = oreDictToTag((String) index.getValue());
					key = new JsonPrimitive(mapped.startsWith("item:") ? mapped.substring("item:".length()) : "#" + mapped);
				} else if (index.getValue() instanceof ItemStack) {
					ItemStack stack = (ItemStack) index.getValue();
					key = new JsonPrimitive(BuiltInRegistries.ITEM.getKey(stack.getItem()).toString());
				} else if (index.getValue() instanceof Item) {
					key = new JsonPrimitive(BuiltInRegistries.ITEM.getKey((Item) index.getValue()).toString());
				} else if (index.getValue() instanceof Block) {
					key = new JsonPrimitive(BuiltInRegistries.ITEM.getKey(Item.BY_BLOCK.get((Block) index.getValue())).toString());
				} else if (index.getValue() instanceof NBTIngredient) {
					key = ((NBTIngredient) index.getValue()).toJson();
				} else {
					logisticspipes.LogisticsPipes.log.warn("Skipping recipe for {}: unhandled ingredient {} for key '{}'",
							BuiltInRegistries.ITEM.getKey(result), index.getValue(), index.getIndex());
					return null;
				}
				keys.add(index.getIndex() + "", key);
			}

			JsonObject r = new JsonObject();
			r.addProperty("id", BuiltInRegistries.ITEM.getKey(result).toString());
			if (count > 1) r.addProperty("count", count);
			obj.add("result", r);
			obj.add("key", keys);
			obj.add("pattern", pattern);

			return GSON.toJson(obj);
		}

		/** Maps 1.12.2 ore dict names to Fabric conventional (c:) tag paths. */
		private static String oreDictToTag(String oreDict) {
			switch (oreDict) {
				case "ingotIron":        return "c:ingots/iron";
				case "ingotGold":        return "c:ingots/gold";
				case "nuggetGold":       return "c:nuggets/gold";
				case "dustRedstone":     return "c:dusts/redstone";
				case "gemLapis":         return "c:gems/lapis";
				case "gemDiamond":       return "c:gems/diamond";
				case "gemQuartz":        return "c:gems/quartz";
				case "dustGlowstone":    return "c:dusts/glowstone";
				case "dyeBlack":         return "c:dyes/black";
				case "dyeRed":           return "c:dyes/red";
				case "dyeGreen":         return "c:dyes/green";
				case "dyeBrown":         return "c:dyes/brown";
				case "dyeBlue":          return "c:dyes/blue";
				case "dyePurple":        return "c:dyes/purple";
				case "dyeCyan":          return "c:dyes/cyan";
				case "dyeLightGray":     return "c:dyes/light_gray";
				case "dyeGray":          return "c:dyes/gray";
				case "dyePink":          return "c:dyes/pink";
				case "dyeLime":          return "c:dyes/lime";
				case "dyeYellow":        return "c:dyes/yellow";
				case "dyeLightBlue":     return "c:dyes/light_blue";
				case "dyeMagenta":       return "c:dyes/magenta";
				case "dyeOrange":        return "c:dyes/orange";
				case "dyeWhite":         return "c:dyes/white";
				case "paper":            return "item:minecraft:paper";
				default:
					// Unknown ore dict — return as conventional tag guess
					return "c:" + oreDict;
			}
		}

		public void addShapelessResetRecipe(Item item, int meta) {
			// meta was a 1.12.2 damage value — ignored in 1.20.1 (no damage-based variants)
			Identifier itemKey = net.minecraft.core.registries.BuiltInRegistries.ITEM.getKey(item);
			if (itemKey == null) return;
			// Own suffix so the reset recipe never collides with the item's craft recipe
			Identifier loc = getFreeRecipeResourceLocation(itemKey.getPath() + "_reset");
			JsonObject json = new JsonObject();
			json.addProperty("type", ShapelessResetRecipe.ID.toString());
			json.addProperty("item", itemKey.toString());
			virtualRecipes.put(loc, new Gson().toJson(json));
		}
	}

	private static Identifier getFreeRecipeResourceLocation(@Nonnull ItemStack stack) {
		return getFreeRecipeResourceLocation(stack.getItem());
	}

	private static Identifier getFreeRecipeResourceLocation(Item item) {
		return getFreeRecipeResourceLocation(BuiltInRegistries.ITEM.getKey(item).getPath());
	}

	private static Identifier getFreeRecipeResourceLocation(String basePath) {
		Identifier recipeLoc = Identifier.fromNamespaceAndPath(LPConstants.LP_MOD_ID, basePath);
		int index = 0;
		while (craftingManager.virtualRecipes.containsKey(recipeLoc)) {
			index++;
			recipeLoc = Identifier.fromNamespaceAndPath(LPConstants.LP_MOD_ID, basePath + "_" + index);
		}
		return recipeLoc;
	}
}
